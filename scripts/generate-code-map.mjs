async function main() {
  const expected = await renderCodeMap();
  if (process.argv.includes('--check')) {
    let actual = '';
    try { actual = await readFile(outputPath, 'utf8'); } catch {}
    if (actual !== expected) {
      console.error('docs/code-map.md is stale. Run: npm run code-map');
      process.exitCode = 1;
      return;
    }
    console.log('Code map is current.');
    return;
  }
  await writeFile(outputPath, expected);
  console.log(`Updated ${path.relative(rootDir, outputPath)}.`);
}

if (path.resolve(process.argv[1] ?? '') === scriptPath) await main();
