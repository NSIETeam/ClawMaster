import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const schemaPath = path.join(root, 'packages/runtime-contracts/schema/v2/runtime-contract.schema.json');
const tsPath = path.join(root, 'packages/runtime-contracts/src/generated.ts');
const rustPath = path.join(root, 'packages/runtime-contracts/generated/runtime_contract_v2.rs');
const checkOnly = process.argv.includes('--check');

const source = await readFile(schemaPath, 'utf8');
const schema = JSON.parse(source);
const defs = schema.$defs;
const digest = createHash('sha256').update(source).digest('hex');

const requiredDefinitions = [
  'RuntimeRequestEnvelope',
  'RuntimeEventEnvelope',
  'RuntimeRequestPayload',
  'RuntimeEventPayload',
  'RuntimeError',
];
if (schema.$schema !== 'https://json-schema.org/draft/2020-12/schema') {
  throw new Error('Runtime Contract source must use JSON Schema 2020-12.');
}
if (!defs || requiredDefinitions.some((name) => !defs[name])) {
  throw new Error('Runtime Contract source is missing a required protocol definition.');
}

function refName(value) {
  return value.$ref?.split('/').at(-1);
}

function tsType(value) {
  if (value.$ref) return refName(value);
  if (Object.hasOwn(value, 'const')) return JSON.stringify(value.const);
  if (value.enum) return value.enum.map((item) => JSON.stringify(item)).join(' | ');
  if (value.oneOf) return value.oneOf.map(tsType).join(' | ');
  if (value.type === 'string') return 'string';
  if (value.type === 'integer' || value.type === 'number') return 'number';
  if (value.type === 'boolean') return 'boolean';
  if (value.type === 'array') return `Array<${tsType(value.items ?? {})}>`;
  if (value.type === 'object') return 'Record<string, unknown>';
  return 'unknown';
}

function tsDefinition(name, value) {
  if (value.type !== 'object') return `export type ${name} = ${tsType(value)};`;
  const required = new Set(value.required ?? []);
  const fields = Object.entries(value.properties ?? {}).map(([field, property]) =>
    `  ${field}${required.has(field) ? '' : '?'}: ${tsType(property)};`,
  );
  return `export interface ${name} {\n${fields.join('\n')}\n}`;
}

const tsDefinitions = Object.entries(defs).map(([name, value]) => tsDefinition(name, value)).join('\n\n');
const requestTypes = unionMembers('RuntimeRequestPayload').map((name) => defs[name].properties.type.const);
const eventTypes = unionMembers('RuntimeEventPayload').map((name) => defs[name].properties.type.const);
const requiredPayloadFields = (unionName) => Object.fromEntries(
  unionMembers(unionName).map((name) => {
    const definition = defs[name];
    return [definition.properties.type.const, definition.required ?? []];
  }),
);
const tsEnumValues = Object.entries(defs)
  .filter(([, value]) => value.enum)
  .map(([name, value]) => `export const ${snakeCase(name).toUpperCase()}_VALUES = ${JSON.stringify(value.enum)} as const;`)
  .join('\n');
const tsOutput = `// @generated by scripts/generate-runtime-contracts.mjs. DO NOT EDIT.\n` +
  `// schema-sha256: ${digest}\n\n` +
  `export const RUNTIME_SCHEMA_VERSION = '2.0.0' as const;\n` +
  `export const RUNTIME_PROTOCOL_VERSION = { major: 2, minor: 0, patch: 0 } as const;\n` +
  `export const RUNTIME_SCHEMA_SHA256 = '${digest}' as const;\n\n` +
  `export const RUNTIME_REQUEST_TYPES = ${JSON.stringify(requestTypes)} as const;\n` +
  `export const RUNTIME_EVENT_TYPES = ${JSON.stringify(eventTypes)} as const;\n\n` +
  `export const RUNTIME_REQUEST_REQUIRED_FIELDS = ${JSON.stringify(requiredPayloadFields('RuntimeRequestPayload'))} as const;\n` +
  `export const RUNTIME_EVENT_REQUIRED_FIELDS = ${JSON.stringify(requiredPayloadFields('RuntimeEventPayload'))} as const;\n\n` +
  `${tsEnumValues}\n\n` +
  `${tsDefinitions}\n`;

function snakeCase(value) {
  return value.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/-/g, '_').toLowerCase();
}

function pascalCase(value) {
  const normalized = value === value.toUpperCase() ? value.toLowerCase() : value;
  return normalized
    .replace(/(^|[_-])(\w)/g, (_, _separator, letter) => letter.toUpperCase());
}

function rustType(value) {
  if (value.$ref) {
    const name = refName(value);
    return name === 'Id' ? 'String' : name;
  }
  if (value.type === 'string' || Object.hasOwn(value, 'const')) return 'String';
  if (value.type === 'integer') return 'u64';
  if (value.type === 'number') return 'f64';
  if (value.type === 'boolean') return 'bool';
  if (value.type === 'array') return `Vec<${rustType(value.items ?? {})}>`;
  if (value.type === 'object') return 'BTreeMap<String, Value>';
  return 'Value';
}

function rustEnum(name, value) {
  const variants = value.enum.map((item) =>
    `    #[serde(rename = ${JSON.stringify(item)})]\n    ${pascalCase(item)},`,
  );
  return `#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]\npub enum ${name} {\n${variants.join('\n')}\n}`;
}

function rustStruct(name, value) {
  const required = new Set(value.required ?? []);
  const fields = Object.entries(value.properties ?? {}).map(([field, property]) => {
    const optional = !required.has(field);
    const attributes = optional ? '    #[serde(default, skip_serializing_if = "Option::is_none")]\n' : '';
    const type = optional ? `Option<${rustType(property)}>` : rustType(property);
    return `${attributes}    pub ${snakeCase(field)}: ${type},`;
  });
  return `#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]\n#[serde(rename_all = "camelCase")]\npub struct ${name} {\n${fields.join('\n')}\n}`;
}

function unionMembers(unionName) {
  return defs[unionName].oneOf.map((entry) => refName(entry));
}

const payloadDefinitions = new Set([
  ...unionMembers('RuntimeRequestPayload'),
  ...unionMembers('RuntimeEventPayload'),
]);

function rustPayloadEnum(name) {
  const variants = unionMembers(name).map((definitionName) => {
    const definition = defs[definitionName];
    const required = new Set(definition.required ?? []);
    const typeValue = definition.properties.type.const;
    const fields = Object.entries(definition.properties)
      .filter(([field]) => field !== 'type')
      .map(([field, property]) => {
        const optional = !required.has(field);
        const attribute = optional ? '        #[serde(default, skip_serializing_if = "Option::is_none")]\n' : '';
        const type = optional ? `Option<${rustType(property)}>` : rustType(property);
        return `${attribute}        ${snakeCase(field)}: ${type},`;
      });
    const body = fields.length ? ` {\n${fields.join('\n')}\n    }` : '';
    return `    #[serde(rename = ${JSON.stringify(typeValue)})]\n    ${pascalCase(typeValue)}${body},`;
  });
  return `#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]\n#[serde(tag = "type", rename_all_fields = "camelCase")]\npub enum ${name} {\n${variants.join('\n')}\n}`;
}

const rustParts = [];
for (const [name, value] of Object.entries(defs)) {
  if (name === 'Id' || payloadDefinitions.has(name)) continue;
  if (name === 'RuntimeRequestPayload' || name === 'RuntimeEventPayload') {
    rustParts.push(rustPayloadEnum(name));
  } else if (value.enum) {
    rustParts.push(rustEnum(name, value));
  } else if (value.type === 'object') {
    rustParts.push(rustStruct(name, value));
  }
}

const rustOutput = `// @generated by scripts/generate-runtime-contracts.mjs. DO NOT EDIT.\n` +
  `// schema-sha256: ${digest}\n\n` +
  `use serde::{Deserialize, Serialize};\n` +
  `use serde_json::Value;\n` +
  `use std::collections::BTreeMap;\n\n` +
  `pub const RUNTIME_SCHEMA_VERSION: &str = "2.0.0";\n` +
  `pub const RUNTIME_SCHEMA_SHA256: &str = "${digest}";\n\n` +
  `pub const RUNTIME_REQUEST_TYPES: &[&str] = &[${requestTypes.map((value) => JSON.stringify(value)).join(', ')}];\n` +
  `pub const RUNTIME_EVENT_TYPES: &[&str] = &[${eventTypes.map((value) => JSON.stringify(value)).join(', ')}];\n\n` +
  `${rustParts.join('\n\n')}\n`;

async function update(target, output) {
  if (!checkOnly) {
    await writeFile(target, output);
    return;
  }
  const current = await readFile(target, 'utf8').catch(() => '');
  if (current !== output) throw new Error(`generated runtime contract is stale: ${path.relative(root, target)}`);
}

await update(tsPath, tsOutput);
await update(rustPath, rustOutput);
console.log(checkOnly ? 'Runtime Contract v2 generated files are current.' : 'Generated Runtime Contract v2 TypeScript and Rust types.');
